%% train_real_cnn_lstm_31800_v1.m
% Train a CNN-LSTM classifier using real PlutoSDR captures only.
%
% Classes:
%   Friendly
%   Adversarial
%
% Dataset:
%   real_sdr_dataset_31800_clean_split.mat
%
% Input:
%   31800 captures
%   256 time samples
%   2 features: I and Q
%
% Preprocessing:
%   1. Remove per-capture I/Q DC offset.
%   2. Normalize each capture by its complex RMS.
%   3. Preserve phase and temporal structure.
%
% Hardware:
%   This script does not use PlutoSDR hardware.
%
% Training:
%   Uses GPU automatically when a supported GPU is available.

clear;
clc;
close all;

rng(42, 'twister');

%% =================================================
% Project paths
% ==================================================

projectFolder = ...
    pwd;

datasetFile = fullfile( ...
    projectFolder, ...
    'results_dataset_31800_clean_split_v2', ...
    'real_sdr_dataset_31800_clean_split.mat');

resultsFolder = fullfile( ...
    projectFolder, ...
    'results_real_cnn_lstm_31800_v1');

modelFile = fullfile( ...
    projectFolder, ...
    'net_real_cnn_lstm_31800_v1.mat');

checkpointFolder = fullfile( ...
    resultsFolder, ...
    'checkpoints');

assert(isfile(datasetFile), ...
    'Clean Dataset file was not found: %s', ...
    datasetFile);

if ~isfolder(resultsFolder)
    mkdir(resultsFolder);
end

if ~isfolder(checkpointFolder)
    mkdir(checkpointFolder);
end

cd(projectFolder);

fprintf('\n');
fprintf('============================================================\n');
fprintf('REAL SDR CNN-LSTM TRAINING V1\n');
fprintf('============================================================\n');
fprintf('STEP TYPE: CNN-LSTM TRAINING\n');
fprintf('Hardware used: NO\n');
fprintf('Physical transmission: NO\n');
fprintf('Physical reception: NO\n');
fprintf('Training data: REAL PLUTOSDR I/Q ONLY\n');
fprintf('Synthetic training captures: NO\n');
fprintf('\nDataset:\n%s\n',datasetFile);
fprintf('\nResults:\n%s\n',resultsFolder);
fprintf('============================================================\n');

%% =================================================
% Load clean Dataset
% ==================================================

fprintf('\nLoading clean Dataset...\n');

D = load(datasetFile);

requiredFields = {
    'realIQ'
    'className'
    'classLabel'
    'modulationName'
    'txUnit'
    'captureOrder'
};

for fieldIndex = 1:numel(requiredFields)

    fieldName = requiredFields{fieldIndex};

    assert(isfield(D,fieldName), ...
        'Required Dataset field is missing: %s', ...
        fieldName);
end

if isfield(D,'cleanSplit')

    splitName = lower(string(D.cleanSplit(:)));

elseif isfield(D,'split')

    splitName = lower(string(D.split(:)));

else

    error('No clean Split variable was found.');
end

realIQ = single(D.realIQ);

className = string(D.className(:));
modulationName = string(D.modulationName(:));
txUnit = string(D.txUnit(:));
captureOrder = double(D.captureOrder(:));

numberOfCaptures = size(realIQ,1);
sequenceLength = size(realIQ,2);
numberOfFeatures = size(realIQ,3);

assert(numberOfCaptures == 31800, ...
    'Expected 31800 captures.');

assert(sequenceLength == 256, ...
    'Expected sequence length 256.');

assert(numberOfFeatures == 2, ...
    'Expected two I/Q features.');

fprintf('Captures: %d\n',numberOfCaptures);
fprintf('Sequence length: %d\n',sequenceLength);
fprintf('Input features: %d\n',numberOfFeatures);

%% =================================================
% Split masks
% ==================================================

trainMask = splitName == "train";

validationMask = ...
    splitName == "validation" ...
    | splitName == "val";

testMask = splitName == "test";

assert(sum(trainMask) == 21000, ...
    'Expected 21000 Training captures.');

assert(sum(validationMask) == 5400, ...
    'Expected 5400 Validation captures.');

assert(sum(testMask) == 5400, ...
    'Expected 5400 Test captures.');

assert(all(trainMask | validationMask | testMask), ...
    'One or more captures have an unknown Split.');

fprintf('\nClean split counts:\n');
fprintf('Training: %d\n',sum(trainMask));
fprintf('Validation: %d\n',sum(validationMask));
fprintf('Test: %d\n',sum(testMask));

%% =================================================
% Preprocess the real I/Q captures
% ==================================================
%
% Each row is one capture:
%   realIQ(row,:,1) = I
%   realIQ(row,:,2) = Q
%
% Remove DC independently from I and Q.
% Normalize using complex RMS:
%   sqrt(mean(I^2 + Q^2))

fprintf('\nPreprocessing real I/Q captures...\n');
fprintf('- Removing per-capture DC offset\n');
fprintf('- Applying per-capture complex RMS normalization\n');

I = realIQ(:,:,1);
Q = realIQ(:,:,2);

meanI = mean(I,2);
meanQ = mean(Q,2);

Icentered = I - meanI;
Qcentered = Q - meanQ;

complexRMS = sqrt( ...
    mean( ...
        Icentered.^2 + Qcentered.^2, ...
        2));

minimumRMS = single(1e-6);

safeRMS = max( ...
    complexRMS, ...
    minimumRMS);

Inormalized = Icentered ./ safeRMS;
Qnormalized = Qcentered ./ safeRMS;

assert(~any(isnan(Inormalized(:))), ...
    'NaN was generated during I normalization.');

assert(~any(isnan(Qnormalized(:))), ...
    'NaN was generated during Q normalization.');

assert(~any(isinf(Inormalized(:))), ...
    'Inf was generated during I normalization.');

assert(~any(isinf(Qnormalized(:))), ...
    'Inf was generated during Q normalization.');

normalizedRMS = sqrt( ...
    mean( ...
        Inormalized.^2 + Qnormalized.^2, ...
        2));

fprintf('Normalized RMS median: %.6f\n', ...
    median(normalizedRMS));

fprintf('Normalized RMS minimum: %.6f\n', ...
    min(normalizedRMS));

fprintf('Normalized RMS maximum: %.6f\n', ...
    max(normalizedRMS));

%% =================================================
% Convert captures to MATLAB sequence cell arrays
% ==================================================
%
% Every cell:
%   2 features x 256 time steps
%
% Feature 1 = I
% Feature 2 = Q

fprintf('\nCreating sequence cell arrays...\n');

allSequences = cell( ...
    numberOfCaptures, ...
    1);

for captureIndex = 1:numberOfCaptures

    allSequences{captureIndex} = single([
        Inormalized(captureIndex,:)
        Qnormalized(captureIndex,:)
    ]);
end

assert(isequal( ...
    size(allSequences{1}), ...
    [2 256]), ...
    'Unexpected sequence dimensions.');

XTrain = allSequences(trainMask);
XValidation = allSequences(validationMask);
XTest = allSequences(testMask);

%% =================================================
% Create categorical labels with fixed class order
% ==================================================

classOrder = [
    "Friendly"
    "Adversarial"
];

YAll = categorical( ...
    className, ...
    classOrder, ...
    classOrder);

YTrain = YAll(trainMask);
YValidation = YAll(validationMask);
YTest = YAll(testMask);

assert(all(~isundefined(YTrain)), ...
    'Training labels contain undefined categories.');

assert(all(~isundefined(YValidation)), ...
    'Validation labels contain undefined categories.');

assert(all(~isundefined(YTest)), ...
    'Test labels contain undefined categories.');

fprintf('\nClass order:\n');
disp(categories(YTrain));

%% =================================================
% Class distribution and class weights
% ==================================================

trainingClassCounts = countcats(YTrain);

numberOfClasses = numel(classOrder);

classWeights = ...
    numel(YTrain) ...
    ./ ( ...
        numberOfClasses ...
        .* double(trainingClassCounts));

% Normalize weights to mean one.
classWeights = ...
    classWeights ...
    / mean(classWeights);

classDistributionTable = table( ...
    classOrder, ...
    trainingClassCounts, ...
    classWeights, ...
    'VariableNames', { ...
        'ClassName', ...
        'TrainingCount', ...
        'ClassWeight' ...
    });

fprintf('\nTraining class distribution and weights:\n');
disp(classDistributionTable);

writetable( ...
    classDistributionTable, ...
    fullfile( ...
        resultsFolder, ...
        'training_class_distribution.csv'));

%% =================================================
% CNN-LSTM architecture
% ==================================================
%
% Input:
%   2 x 256 sequence
%
% CNN:
%   Learns local waveform structures.
%
% LSTM:
%   Learns temporal dependencies across the sequence.
%
% Output:
%   Friendly / Adversarial

layers = [
    sequenceInputLayer( ...
        numberOfFeatures, ...
        'Normalization', ...
        'none', ...
        'MinLength', ...
        sequenceLength, ...
        'Name', ...
        'iq_input')

    convolution1dLayer( ...
        7, ...
        64, ...
        'Padding', ...
        'same', ...
        'Name', ...
        'conv1')

    batchNormalizationLayer( ...
        'Name', ...
        'bn1')

    reluLayer( ...
        'Name', ...
        'relu1')

    maxPooling1dLayer( ...
        2, ...
        'Stride', ...
        2, ...
        'Name', ...
        'pool1')

    convolution1dLayer( ...
        5, ...
        128, ...
        'Padding', ...
        'same', ...
        'Name', ...
        'conv2')

    batchNormalizationLayer( ...
        'Name', ...
        'bn2')

    reluLayer( ...
        'Name', ...
        'relu2')

    maxPooling1dLayer( ...
        2, ...
        'Stride', ...
        2, ...
        'Name', ...
        'pool2')

    convolution1dLayer( ...
        3, ...
        128, ...
        'Padding', ...
        'same', ...
        'Name', ...
        'conv3')

    batchNormalizationLayer( ...
        'Name', ...
        'bn3')

    reluLayer( ...
        'Name', ...
        'relu3')

    dropoutLayer( ...
        0.20, ...
        'Name', ...
        'cnn_dropout')

    lstmLayer( ...
        128, ...
        'OutputMode', ...
        'last', ...
        'Name', ...
        'lstm')

    dropoutLayer( ...
        0.35, ...
        'Name', ...
        'lstm_dropout')

    fullyConnectedLayer( ...
        64, ...
        'Name', ...
        'fc1')

    reluLayer( ...
        'Name', ...
        'fc_relu')

    dropoutLayer( ...
        0.25, ...
        'Name', ...
        'fc_dropout')

    fullyConnectedLayer( ...
        numberOfClasses, ...
        'Name', ...
        'class_scores')

    softmaxLayer( ...
        'Name', ...
        'softmax')

    classificationLayer( ...
        'Name', ...
        'weighted_output', ...
        'Classes', ...
        classOrder, ...
        'ClassWeights', ...
        classWeights)
];

fprintf('\nCNN-LSTM architecture:\n');
disp(layers);

%% =================================================
% GPU selection
% ==================================================

useGPU = false;
gpuName = "CPU";

try

    if canUseGPU

        gpuInformation = gpuDevice;

        useGPU = true;
        gpuName = string(gpuInformation.Name);

        reset(gpuInformation);
    end

catch gpuException

    warning( ...
        'GPU check failed. CPU will be used: %s', ...
        gpuException.message);
end

if useGPU

    executionEnvironment = 'gpu';

else

    executionEnvironment = 'cpu';
end

fprintf('\nExecution environment: %s\n', ...
    executionEnvironment);

fprintf('Device: %s\n',gpuName);

%% =================================================
% Training configuration
% ==================================================

miniBatchSize = 128;
maximumEpochs = 40;

iterationsPerEpoch = ceil( ...
    numel(XTrain) ...
    / miniBatchSize);

validationFrequency = max( ...
    1, ...
    floor(iterationsPerEpoch / 2));

fprintf('\nTraining configuration:\n');
fprintf('Maximum epochs: %d\n',maximumEpochs);
fprintf('Mini-batch size: %d\n',miniBatchSize);
fprintf('Iterations per epoch: %d\n',iterationsPerEpoch);
fprintf('Validation frequency: %d iterations\n', ...
    validationFrequency);

options = trainingOptions( ...
    'adam', ...
    'ExecutionEnvironment', ...
    executionEnvironment, ...
    'MaxEpochs', ...
    maximumEpochs, ...
    'MiniBatchSize', ...
    miniBatchSize, ...
    'InitialLearnRate', ...
    1e-3, ...
    'LearnRateSchedule', ...
    'piecewise', ...
    'LearnRateDropPeriod', ...
    8, ...
    'LearnRateDropFactor', ...
    0.5, ...
    'GradientThreshold', ...
    1, ...
    'L2Regularization', ...
    1e-4, ...
    'Shuffle', ...
    'every-epoch', ...
    'ValidationData', ...
    {XValidation, YValidation}, ...
    'ValidationFrequency', ...
    validationFrequency, ...
    'ValidationPatience', ...
    8, ...
    'OutputNetwork', ...
    'best-validation-loss', ...
    'CheckpointPath', ...
    checkpointFolder, ...
    'Verbose', ...
    true, ...
    'VerboseFrequency', ...
    validationFrequency, ...
    'Plots', ...
    'training-progress');

%% =================================================
% Train CNN-LSTM
% ==================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('STARTING CNN-LSTM TRAINING\n');
fprintf('============================================================\n');

trainingStartTime = datetime('now');

trainingTimer = tic;

[netRealCNNLSTM, trainingInfo] = trainNetwork( ...
    XTrain, ...
    YTrain, ...
    layers, ...
    options);

trainingElapsedSeconds = toc( ...
    trainingTimer);

trainingEndTime = datetime('now');

fprintf('\nTraining completed.\n');
fprintf('Elapsed time: %.2f minutes\n', ...
    trainingElapsedSeconds / 60);

%% =================================================
% Validation evaluation
% ==================================================

fprintf('\nEvaluating Validation split...\n');

[YValidationPrediction, validationScores] = classify( ...
    netRealCNNLSTM, ...
    XValidation, ...
    'MiniBatchSize', ...
    miniBatchSize, ...
    'ExecutionEnvironment', ...
    executionEnvironment);

validationAccuracy = mean( ...
    YValidationPrediction == YValidation) * 100;

%% =================================================
% Test evaluation
% ==================================================

fprintf('Evaluating independent Test split...\n');

[YTestPrediction, testScores] = classify( ...
    netRealCNNLSTM, ...
    XTest, ...
    'MiniBatchSize', ...
    miniBatchSize, ...
    'ExecutionEnvironment', ...
    executionEnvironment);

testAccuracy = mean( ...
    YTestPrediction == YTest) * 100;

%% =================================================
% Confusion matrices
% ==================================================

confusionOrder = categorical( ...
    classOrder, ...
    classOrder, ...
    classOrder);

validationConfusionMatrix = confusionmat( ...
    YValidation, ...
    YValidationPrediction, ...
    'Order', ...
    confusionOrder);

testConfusionMatrix = confusionmat( ...
    YTest, ...
    YTestPrediction, ...
    'Order', ...
    confusionOrder);

%% =================================================
% Binary metrics
% ==================================================
%
% Positive class:
%   Adversarial

friendlyIndex = 1;
adversarialIndex = 2;

trueNegative = ...
    testConfusionMatrix(friendlyIndex,friendlyIndex);

falsePositive = ...
    testConfusionMatrix(friendlyIndex,adversarialIndex);

falseNegative = ...
    testConfusionMatrix(adversarialIndex,friendlyIndex);

truePositive = ...
    testConfusionMatrix(adversarialIndex,adversarialIndex);

adversarialRecall = ...
    truePositive ...
    / max(truePositive + falseNegative,1);

adversarialPrecision = ...
    truePositive ...
    / max(truePositive + falsePositive,1);

adversarialF1 = ...
    2 ...
    * adversarialPrecision ...
    * adversarialRecall ...
    / max( ...
        adversarialPrecision ...
        + adversarialRecall, ...
        eps);

friendlyRecall = ...
    trueNegative ...
    / max(trueNegative + falsePositive,1);

specificity = friendlyRecall;

balancedAccuracy = ...
    0.5 ...
    * (adversarialRecall + specificity);

falseAlarmRate = ...
    falsePositive ...
    / max(falsePositive + trueNegative,1);

missRate = ...
    falseNegative ...
    / max(falseNegative + truePositive,1);

%% =================================================
% Summary table
% ==================================================

trainingSummary = table( ...
    numberOfCaptures, ...
