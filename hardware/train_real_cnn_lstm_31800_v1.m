    gpuName, ...
    trainingElapsedSeconds, ...
    validationAccuracy, ...
    testAccuracy, ...
    adversarialRecall * 100, ...
    adversarialPrecision * 100, ...
    adversarialF1 * 100, ...
    friendlyRecall * 100, ...
    balancedAccuracy * 100, ...
    falseAlarmRate * 100, ...
    missRate * 100, ...
    trueNegative, ...
    falsePositive, ...
    falseNegative, ...
    truePositive, ...
    'VariableNames', { ...
        'TotalCaptures', ...
        'TrainingCaptures', ...
        'ValidationCaptures', ...
        'TestCaptures', ...
        'MaximumEpochs', ...
        'MiniBatchSize', ...
        'ExecutionEnvironment', ...
        'DeviceName', ...
        'TrainingElapsedSeconds', ...
        'ValidationAccuracyPct', ...
        'TestAccuracyPct', ...
        'AdversarialRecallPct', ...
        'AdversarialPrecisionPct', ...
        'AdversarialF1Pct', ...
        'FriendlyRecallPct', ...
        'BalancedAccuracyPct', ...
        'FalseAlarmRatePct', ...
        'MissRatePct', ...
        'TrueNegative', ...
        'FalsePositive', ...
        'FalseNegative', ...
        'TruePositive' ...
    });

fprintf('\n');
fprintf('============================================================\n');
fprintf('REAL CNN-LSTM RESULTS\n');
fprintf('============================================================\n');

fprintf('Validation accuracy: %.2f%%\n', ...
    validationAccuracy);

fprintf('Test accuracy: %.2f%%\n', ...
    testAccuracy);

fprintf('Balanced accuracy: %.2f%%\n', ...
    balancedAccuracy * 100);

fprintf('Friendly recall: %.2f%%\n', ...
    friendlyRecall * 100);

fprintf('Adversarial recall: %.2f%%\n', ...
    adversarialRecall * 100);

fprintf('Adversarial precision: %.2f%%\n', ...
    adversarialPrecision * 100);

fprintf('Adversarial F1: %.2f%%\n', ...
    adversarialF1 * 100);

fprintf('False alarm rate: %.2f%%\n', ...
    falseAlarmRate * 100);

fprintf('Miss rate: %.2f%%\n', ...
    missRate * 100);

fprintf('\nTest confusion matrix:\n');
disp(array2table( ...
    testConfusionMatrix, ...
