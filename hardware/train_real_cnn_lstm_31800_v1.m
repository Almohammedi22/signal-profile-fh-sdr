    YValidation == YValidationPrediction, ...
    'VariableNames', { ...
        'CaptureOrder', ...
        'ModulationName', ...
        'TxUnit', ...
        'TrueClass', ...
        'PredictedClass', ...
        'Confidence', ...
        'Correct' ...
    });

testResults = table( ...
    captureOrder(testMask), ...
    modulationName(testMask), ...
