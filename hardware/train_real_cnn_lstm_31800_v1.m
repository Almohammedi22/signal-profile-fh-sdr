    YTest == YTestPrediction, ...
    'VariableNames', { ...
        'CaptureOrder', ...
        'ModulationName', ...
        'TxUnit', ...
        'TrueClass', ...
        'PredictedClass', ...
        'Confidence', ...
        'Correct' ...
    });

writetable( ...
    validationResults, ...
    fullfile( ...
        resultsFolder, ...
        'validation_predictions.csv'));

writetable( ...
    testResults, ...
    fullfile( ...
        resultsFolder, ...
        'test_predictions.csv'));

save( ...
