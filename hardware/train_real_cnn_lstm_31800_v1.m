for modulationIndex = 1:numel(uniqueTestModulations)

    currentModulation = ...
        uniqueTestModulations(modulationIndex);

    currentMask = ...
        testModulation == currentModulation;

    modulationRows{modulationIndex} = table( ...
        currentModulation, ...
        sum(currentMask), ...
        mean(testCorrect(currentMask)) * 100, ...
