%% train_cnn_lstm_occ_v5.m
% CNN-LSTM binary classifier:
% friendly versus adversarial
% Training is forced to use the NVIDIA GPU.

clear;
clc;
close all;

%% Paths and required files

trainingFolder = ...
    pwd;

cd(trainingFolder);

sequenceFile = 'occupied_sequences_v5.mat';

if ~isfile(sequenceFile)
    error('Required file not found: %s', sequenceFile);
end

%% Verify GPU

if ~canUseGPU
    error([ ...
        'A supported GPU is not available. ' ...
        'Check the NVIDIA driver and Parallel Computing Toolbox.' ...
        ]);
end

reset(gpuDevice);

gpuInfo = gpuDevice(1);

fprintf('\n============================================\n');
fprintf('CNN-LSTM OCCUPIED CLASSIFIER TRAINING\n');
fprintf('============================================\n');
fprintf('Execution device: %s\n', gpuInfo.Name);
fprintf('Compute capability: %s\n', ...
    gpuInfo.ComputeCapability);
fprintf('Available GPU memory: %.2f GB\n', ...
    gpuInfo.AvailableMemory / 1024^3);
fprintf('============================================\n\n');

%% Load prepared sequences

data = load(sequenceFile);

requiredVariables = {
    'XTrain'
    'YTrain'
    'XValidation'
    'YValidation'
    'XTest'
    'YTest'
};

for k = 1:numel(requiredVariables)

    variableName = requiredVariables{k};

    if ~isfield(data, variableName)
        error( ...
            'Variable "%s" was not found in %s.', ...
            variableName, ...
            sequenceFile);
    end
end

XTrain = data.XTrain;
YTrain = data.YTrain(:);

XValidation = data.XValidation;
YValidation = data.YValidation(:);

XTest = data.XTest;
YTest = data.YTest(:);

fprintf('Training sequences: %d\n', numel(XTrain));
fprintf('Validation sequences: %d\n', numel(XValidation));
fprintf('Test sequences: %d\n', numel(XTest));

fprintf('\nTraining class distribution:\n');
disp(countcats(YTrain));

fprintf('Validation class distribution:\n');
disp(countcats(YValidation));

fprintf('Test class distribution:\n');
disp(countcats(YTest));

%% Validate one sequence

firstSequenceSize = size(XTrain{1});

fprintf( ...
    'Sequence format: %s\n', ...
    mat2str(firstSequenceSize));

if ~isequal(firstSequenceSize, [2 256])
    error([ ...
        'Unexpected sequence shape. ' ...
        'Expected 2-by-256 but received %s.' ...
        ], ...
        mat2str(firstSequenceSize));
end

%% CNN-LSTM architecture

numberOfFeatures = 2;
numberOfClasses = 2;

layers = [
   sequenceInputLayer( ...
    numberOfFeatures, ...
    'Name', 'sequence_input', ...
    'Normalization', 'none', ...
    'MinLength', 256)

    convolution1dLayer( ...
        7, ...
        64, ...
        'Padding', 'same', ...
        'Name', 'conv_1')

    batchNormalizationLayer( ...
        'Name', 'batch_norm_1')

    reluLayer( ...
        'Name', 'relu_1')

    maxPooling1dLayer( ...
        2, ...
        'Stride', 2, ...
        'Name', 'max_pool_1')

    convolution1dLayer( ...
        5, ...
        128, ...
        'Padding', 'same', ...
        'Name', 'conv_2')

    batchNormalizationLayer( ...
        'Name', 'batch_norm_2')

    reluLayer( ...
        'Name', 'relu_2')

    dropoutLayer( ...
        0.25, ...
        'Name', 'dropout_1')

    lstmLayer( ...
        96, ...
        'OutputMode', 'last', ...
        'Name', 'lstm')

    dropoutLayer( ...
        0.35, ...
        'Name', 'dropout_2')

    fullyConnectedLayer( ...
        64, ...
        'Name', 'fully_connected_1')

    reluLayer( ...
        'Name', 'relu_3')

    dropoutLayer( ...
        0.25, ...
        'Name', 'dropout_3')

    fullyConnectedLayer( ...
        numberOfClasses, ...
        'Name', 'fully_connected_output')

    softmaxLayer( ...
        'Name', 'softmax')

    classificationLayer( ...
        'Name', 'classification')
];

%% Training options

maxEpochs = 25;
miniBatchSize = 256;

iterationsPerEpoch = max( ...
    1, ...
    floor(numel(XTrain) / miniBatchSize));

validationFrequency = max( ...
    1, ...
    iterationsPerEpoch);

options = trainingOptions( ...
    'adam', ...
    'ExecutionEnvironment', 'gpu', ...
    'MaxEpochs', maxEpochs, ...
    'MiniBatchSize', miniBatchSize, ...
    'InitialLearnRate', 1e-3, ...
    'GradientThreshold', 1, ...
    'L2Regularization', 1e-4, ...
    'Shuffle', 'every-epoch', ...
    'ValidationData', {XValidation, YValidation}, ...
    'ValidationFrequency', validationFrequency, ...
    'ValidationPatience', Inf, ...
    'Verbose', true, ...
    'VerboseFrequency', validationFrequency, ...
    'Plots', 'training-progress', ...
    'OutputNetwork', 'last-iteration');

fprintf('\nTraining configuration:\n');
fprintf('Epochs: %d\n', maxEpochs);
fprintf('Mini-batch size: %d\n', miniBatchSize);
fprintf('Iterations per epoch: %d\n', iterationsPerEpoch);
fprintf('Validation frequency: %d\n', validationFrequency);
fprintf('Early stopping: disabled\n');
fprintf('Execution environment: GPU\n\n');

%% Train model

trainingStart = tic;

[netCNNLSTMocc, trainingInfo] = trainNetwork( ...
    XTrain, ...
    YTrain, ...
    layers, ...
    options);

trainingTimeSeconds = toc(trainingStart);

fprintf('\nCNN-LSTM training completed.\n');
fprintf('Training time: %.2f seconds\n', ...
    trainingTimeSeconds);

%% Evaluate on untouched test split

fprintf('\nClassifying test split on GPU...\n');

YPred = classify( ...
    netCNNLSTMocc, ...
    XTest, ...
    'MiniBatchSize', miniBatchSize, ...
    'ExecutionEnvironment', 'gpu');

YPred = YPred(:);
YTest = YTest(:);

accCNNLSTMocc = mean( ...
    YPred == YTest);

fprintf('\n============================================\n');
fprintf('CNN-LSTM OCCUPIED TEST RESULTS\n');
fprintf('============================================\n');
fprintf('Test accuracy: %.2f%%\n', ...
    accCNNLSTMocc * 100);
fprintf('Test samples: %d\n', ...
    numel(YTest));
fprintf('Training time: %.2f seconds\n', ...
    trainingTimeSeconds);

%% Confusion matrix

classNames = [
    "friendly"
    "adversarial"
];

categoryOrder = categorical( ...
    classNames, ...
    classNames);

confusionMatrixCNNLSTMocc = confusionmat( ...
    YTest, ...
    YPred, ...
    'Order', categoryOrder);

fprintf('\nConfusion matrix:\n');
fprintf('Rows = true, columns = predicted\n');
fprintf('Order = friendly, adversarial\n\n');

confusionTable = array2table( ...
    confusionMatrixCNNLSTMocc, ...
    'VariableNames', cellstr(classNames), ...
    'RowNames', cellstr(classNames));

disp(confusionTable);

%% Class-specific metrics

nFriendly = sum(YTest == "friendly");
nAdversarial = sum(YTest == "adversarial");

friendlyAccuracy = NaN;
adversarialAccuracy = NaN;

if nFriendly > 0
    friendlyAccuracy = ...
        confusionMatrixCNNLSTMocc(1,1) ...
        / nFriendly;
end

if nAdversarial > 0
    adversarialAccuracy = ...
        confusionMatrixCNNLSTMocc(2,2) ...
        / nAdversarial;
end

fprintf( ...
    'Friendly recall: %.2f%%\n', ...
    friendlyAccuracy * 100);

fprintf( ...
    'Adversarial recall: %.2f%%\n', ...
    adversarialAccuracy * 100);

%% Confusion chart

figure('Color', 'white');

chart = confusionchart( ...
    YTest, ...
    YPred);

chart.Title = sprintf( ...
    'CNN-LSTM Occupied Test Accuracy: %.2f%%', ...
    accCNNLSTMocc * 100);

chart.RowSummary = 'row-normalized';
chart.ColumnSummary = 'column-normalized';

exportgraphics( ...
    gcf, ...
    'confusion_cnn_lstm_occ_v5.png', ...
    'Resolution', 200);

%% Save prediction table

predictionTable = table( ...
    string(YTest), ...
    string(YPred), ...
    double(YTest == YPred), ...
    'VariableNames', { ...
        'TrueLabel', ...
        'PredictedLabel', ...
        'Correct' ...
        });

writetable( ...
    predictionTable, ...
    'cnn_lstm_occ_v5_test_predictions.csv');

%% Save summary

resultsTable = table( ...
    accCNNLSTMocc * 100, ...
    friendlyAccuracy * 100, ...
    adversarialAccuracy * 100, ...
    numel(YTest), ...
    maxEpochs, ...
    miniBatchSize, ...
    trainingTimeSeconds, ...
    string(gpuInfo.Name), ...
    'VariableNames', { ...
        'TestAccuracyPercent', ...
        'FriendlyRecallPercent', ...
        'AdversarialRecallPercent', ...
        'TestSamples', ...
        'Epochs', ...
        'MiniBatchSize', ...
        'TrainingTimeSeconds', ...
        'GPU' ...
        });

writetable( ...
    resultsTable, ...
    'cnn_lstm_occ_v5_results.csv');

%% Save network file required by SDR validation

save( ...
    'net_cnn_lstm_occ_v5.mat', ...
    'netCNNLSTMocc', ...
    'accCNNLSTMocc', ...
    'trainingInfo', ...
    'trainingTimeSeconds', ...
    'confusionMatrixCNNLSTMocc', ...
    'friendlyAccuracy', ...
    'adversarialAccuracy', ...
    'classNames', ...
    '-v7.3');

fprintf('\nSaved files:\n');
fprintf('- net_cnn_lstm_occ_v5.mat\n');
fprintf('- confusion_cnn_lstm_occ_v5.png\n');
fprintf('- cnn_lstm_occ_v5_results.csv\n');
fprintf('- cnn_lstm_occ_v5_test_predictions.csv\n');
