%% =================================================
% Local function: FH pattern name
% ==================================================

function patternName = getPatternName( ...
    patternID, ...
    datasetStruct)

    patternID = double(patternID);

    if patternID == 0

        patternName = ...
            "No_FH_or_unassigned";

        return;
    end

    if isfield(datasetStruct, 'fhPatternNames')

        names = ...
            datasetStruct.fhPatternNames;

        try

            if iscell(names)

                if patternID >= 1 && ...
                        patternID <= numel(names)

                    patternName = string( ...
                        names{patternID});

                    return;
                end

            elseif isstring(names)

                if patternID >= 1 && ...
                        patternID <= numel(names)

                    patternName = ...
                        names(patternID);

                    return;
                end
            end

        catch
        end
    end

    defaultNames = [
        "Static"
        "Sequential"
        "Random"
        "PseudoRandom"
        "Adaptive"
        "FriendlyFH"
        "AdversarialFH"
        "FastFH"
        "SlowFH"
        "HybridFH"
    ];

    if patternID >= 1 && ...
            patternID <= numel(defaultNames)

        patternName = ...
            defaultNames(patternID);

    else

        patternName = ...
            "UnknownPattern_" ...
            + string(patternID);
    end
end