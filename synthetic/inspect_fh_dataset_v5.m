%% =================================================
% Training-memory lookup baseline
% ==================================================
%
% For a test history seen during training, predict the most frequent
% training target associated with that exact history.
%
% This establishes whether exact memorization can solve the task.

historyTrain = history( ...
    trainIndices, ...
    :);

targetTrain = targets( ...
    trainIndices);

[uniqueTrainHistories, ~, trainGroupID] = unique( ...
    historyTrain, ...
    'rows', ...
    'stable');

numberOfTrainGroups = size( ...
    uniqueTrainHistories, ...
    1);

trainGroupTargetMode = zeros( ...
    numberOfTrainGroups, ...
    1);

for groupIndex = 1:numberOfTrainGroups

    groupTargets = targetTrain( ...
        trainGroupID == groupIndex);

    trainGroupTargetMode(groupIndex) = ...
        mode(groupTargets);
end

[testHistoryFound, testHistoryTrainLocation] = ismember( ...
    historyTest, ...
    uniqueTrainHistories, ...
    'rows');

lookupPrediction = nan( ...
    numel(testIndices), ...
    1);

lookupPrediction(testHistoryFound) = ...
    trainGroupTargetMode( ...
        testHistoryTrainLocation(testHistoryFound));

numberOfTestHistoriesSeenInTraining = sum( ...
    testHistoryFound);

testHistoryOverlapPercentage = ...
    numberOfTestHistoriesSeenInTraining ...
    / numel(testIndices) ...
    * 100;

if any(testHistoryFound)

    lookupAccuracyOnSeen = mean( ...
        lookupPrediction(testHistoryFound) ...
        == targetTest(testHistoryFound)) ...
        * 100;

    lookupMeanErrorOnSeen = mean(abs( ...
        lookupPrediction(testHistoryFound) ...
        - targetTest(testHistoryFound)));

else

    lookupAccuracyOnSeen = NaN;
    lookupMeanErrorOnSeen = NaN;
end

fprintf('\n');
fprintf('============================================\n');
fprintf('TRAIN-TO-TEST HISTORY LOOKUP\n');
fprintf('============================================\n');

fprintf('Test histories seen exactly in training: %d / %d\n', ...
    numberOfTestHistoriesSeenInTraining, ...
    numel(testIndices));

fprintf('Exact-history overlap: %.2f%%\n', ...
    testHistoryOverlapPercentage);

fprintf('Lookup accuracy on seen histories: %.2f%%\n', ...
    lookupAccuracyOnSeen);

fprintf('Lookup mean error on seen histories: %.2f\n', ...
    lookupMeanErrorOnSeen);

fprintf('============================================\n');

lookupSummary = table( ...
    numel(testIndices), ...
    numberOfTestHistoriesSeenInTraining, ...
    testHistoryOverlapPercentage, ...
    lookupAccuracyOnSeen, ...
    lookupMeanErrorOnSeen, ...
    'VariableNames', { ...
        'TestSamples', ...
        'HistoriesSeenInTraining', ...
        'HistoryOverlapPct', ...
        'LookupAccuracyOnSeenPct', ...
        'LookupMeanAbsoluteErrorOnSeen' ...
    });

writetable( ...
    lookupSummary, ...
    fullfile( ...
        resultsFolder, ...
        'fh_train_test_history_lookup.csv'));

%% =================================================
% First-order transition baseline
% ==================================================
%
% Estimate P(next channel | current channel) from training data.

transitionCounts = zeros( ...
    numberOfChannels, ...
    numberOfChannels);

for trainingRowIndex = 1:numel(trainIndices)

    currentChannel = round( ...
        historyTrain(trainingRowIndex, end));

    nextChannel = round( ...
        targetTrain(trainingRowIndex));

    if currentChannel >= 1 && ...
            currentChannel <= numberOfChannels && ...
            nextChannel >= 1 && ...
            nextChannel <= numberOfChannels

        transitionCounts( ...
            currentChannel, ...
            nextChannel) = ...
            transitionCounts( ...
                currentChannel, ...
                nextChannel) + 1;
    end
end

transitionPrediction = zeros( ...
    numel(testIndices), ...
    1);

globalTargetMode = mode( ...
    targetTrain);

for testRowIndex = 1:numel(testIndices)

    currentChannel = round( ...
        historyTest(testRowIndex, end));

    if currentChannel >= 1 && ...
            currentChannel <= numberOfChannels && ...
            any(transitionCounts(currentChannel, :) > 0)

        [~, predictedChannel] = max( ...
            transitionCounts(currentChannel, :));

        transitionPrediction(testRowIndex) = ...
            predictedChannel;

    else

        transitionPrediction(testRowIndex) = ...
            globalTargetMode;
    end
end

transitionAccuracy = mean( ...
    transitionPrediction == targetTest) * 100;

transitionMeanError = mean(abs( ...
    transitionPrediction - targetTest));

fprintf('\n');
fprintf('============================================\n');
fprintf('FIRST-ORDER TRANSITION BASELINE\n');
fprintf('============================================\n');

fprintf('Accuracy: %.2f%%\n', ...
    transitionAccuracy);

fprintf('Mean absolute channel error: %.2f\n', ...
    transitionMeanError);

fprintf('============================================\n');

transitionSummary = table( ...
    transitionAccuracy, ...
    transitionMeanError, ...
    'VariableNames', { ...
        'AccuracyPct', ...
        'MeanAbsoluteError' ...
    });

writetable( ...
    transitionSummary, ...
    fullfile( ...
        resultsFolder, ...
        'fh_transition_baseline.csv'));

