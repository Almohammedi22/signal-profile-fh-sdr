%% inspect_fh_dataset_v5.m
% Complete inspection of the Frequency-Hopping variables in dataset_v5.
%
% The script checks:
%   1. Required variables and dimensions.
%   2. Channel and label ranges.
%   3. History direction using simple baselines.
%   4. Accuracy by FH pattern.
%   5. Static and Sequential examples.
%   6. Ambiguous histories with conflicting next-hop targets.
%   7. Train/test history overlap.
%   8. Transition predictability.
%   9. CSV and MAT output files.
%
% No model training is performed by this script.

clear;
clc;
close all;

%% =================================================
% Project configuration
% ==================================================

projectFolder = ...
    pwd;

datasetFile = fullfile( ...
    projectFolder, ...
    'dataset_v5.mat');

resultsFolder = fullfile( ...
    projectFolder, ...
    'results_fh_inspection');

cd(projectFolder);

if ~isfolder(resultsFolder)
    mkdir(resultsFolder);
end

if ~isfile(datasetFile)
    error('Dataset file was not found: %s', datasetFile);
end

fprintf('\n');
fprintf('============================================\n');
fprintf('FH DATASET V5 INSPECTION\n');
fprintf('============================================\n');
fprintf('Dataset:\n%s\n', datasetFile);
fprintf('Results folder:\n%s\n', resultsFolder);
fprintf('============================================\n');

%% =================================================
% Inspect available variables
% ==================================================

datasetVariables = whos( ...
    '-file', ...
    datasetFile);

fprintf('\nAvailable dataset variables:\n');

for variableIndex = 1:numel(datasetVariables)

    fprintf( ...
        '%-28s | %-12s | %s\n', ...
        datasetVariables(variableIndex).name, ...
        datasetVariables(variableIndex).class, ...
        mat2str(datasetVariables(variableIndex).size));
end

availableNames = string( ...
    {datasetVariables.name});

%% =================================================
% Required variables
% ==================================================

requiredVariables = [
    "channel_history"
    "y_next_hop"
    "y_fh_pattern"
    "test_idx"
];

for variableIndex = 1:numel(requiredVariables)

    if ~ismember( ...
            requiredVariables(variableIndex), ...
            availableNames)

        error( ...
            'Required variable is missing: %s', ...
            requiredVariables(variableIndex));
    end
end

%% =================================================
% Load FH variables
% ==================================================

variablesToLoad = {
    'channel_history'
    'y_next_hop'
    'y_fh_pattern'
    'test_idx'
};

optionalVariables = [
    "train_idx"
    "val_idx"
    "K"
    "fhPatternNames"
    "episode_id"
    "time_slot"
    "system"
    "system_id"
];

for variableIndex = 1:numel(optionalVariables)

    if ismember( ...
            optionalVariables(variableIndex), ...
            availableNames)

        variablesToLoad{end + 1} = ...
            char(optionalVariables(variableIndex));
    end
end

D = load( ...
    datasetFile, ...
    variablesToLoad{:});

history = double( ...
    D.channel_history);

targets = double( ...
    D.y_next_hop(:));

patterns = double( ...
    D.y_fh_pattern(:));

testIndices = double( ...
    D.test_idx(:));

numberOfSamples = size( ...
    history, ...
    1);

historyLength = size( ...
    history, ...
    2);

%% =================================================
% Validate dimensions
% ==================================================

if numel(targets) ~= numberOfSamples
    error('y_next_hop length does not match channel_history.');
end

if numel(patterns) ~= numberOfSamples
    error('y_fh_pattern length does not match channel_history.');
end

if any(testIndices < 1) || ...
        any(testIndices > numberOfSamples)

    error('test_idx contains invalid indices.');
end

fprintf('\n');
fprintf('============================================\n');
fprintf('DATASET DIMENSIONS\n');
fprintf('============================================\n');

fprintf('Total samples: %d\n', ...
    numberOfSamples);

fprintf('History length: %d\n', ...
    historyLength);

fprintf('Test samples: %d\n', ...
    numel(testIndices));

if isfield(D, 'train_idx')

    trainIndices = double( ...
        D.train_idx(:));

    fprintf('Training samples: %d\n', ...
        numel(trainIndices));

else

    allIndices = (1:numberOfSamples).';

    trainIndices = setdiff( ...
        allIndices, ...
        testIndices);

    fprintf( ...
        ['train_idx was not available. ' ...
         'Using all non-test samples as training data: %d\n'], ...
        numel(trainIndices));
end

if isfield(D, 'val_idx')

    validationIndices = double( ...
        D.val_idx(:));

    fprintf('Validation samples: %d\n', ...
        numel(validationIndices));

else

    validationIndices = [];
end

fprintf('============================================\n');

%% =================================================
% Basic ranges and invalid values
% ==================================================

historyMinimum = min( ...
    history, ...
    [], ...
    'all');

historyMaximum = max( ...
    history, ...
    [], ...
    'all');

targetMinimum = min( ...
    targets);

targetMaximum = max( ...
    targets);

patternMinimum = min( ...
    patterns);

patternMaximum = max( ...
    patterns);

historyNonIntegerCount = sum( ...
    abs(history - round(history)) > 1e-9, ...
    'all');

targetNonIntegerCount = sum( ...
    abs(targets - round(targets)) > 1e-9);

historyNaNCount = sum( ...
    isnan(history), ...
    'all');

targetNaNCount = sum( ...
    isnan(targets));

fprintf('\n');
fprintf('============================================\n');
fprintf('VALUE RANGES\n');
fprintf('============================================\n');

fprintf('History channel range: %.0f to %.0f\n', ...
    historyMinimum, ...
    historyMaximum);

fprintf('Target channel range: %.0f to %.0f\n', ...
    targetMinimum, ...
    targetMaximum);

fprintf('FH pattern range: %.0f to %.0f\n', ...
    patternMinimum, ...
    patternMaximum);

fprintf('History NaN values: %d\n', ...
    historyNaNCount);

fprintf('Target NaN values: %d\n', ...
    targetNaNCount);

fprintf('Non-integer history values: %d\n', ...
    historyNonIntegerCount);

fprintf('Non-integer targets: %d\n', ...
    targetNonIntegerCount);

fprintf('============================================\n');

%% =================================================
% Test-set arrays
% ==================================================

historyTest = history( ...
    testIndices, ...
    :);

targetTest = targets( ...
    testIndices);

patternTest = patterns( ...
    testIndices);

%% =================================================
% Define simple predictions
% ==================================================

predictionFirst = historyTest(:, 1);

predictionLast = historyTest(:, end);

predictionMode = mode( ...
    historyTest, ...
    2);

if historyLength >= 2

    lastDifference = ...
        historyTest(:, end) ...
        - historyTest(:, end - 1);

    predictionLinearForward = ...
        historyTest(:, end) ...
        + lastDifference;

    firstDifference = ...
        historyTest(:, 1) ...
        - historyTest(:, 2);

    predictionLinearReverse = ...
        historyTest(:, 1) ...
        + firstDifference;

else

    predictionLinearForward = ...
        predictionLast;

    predictionLinearReverse = ...
        predictionFirst;
end

%% =================================================
% Wrap sequential predictions to observed channel range
% ==================================================

numberOfChannels = max( ...
    historyMaximum, ...
    targetMaximum);

predictionLinearForwardWrapped = mod( ...
    predictionLinearForward - 1, ...
    numberOfChannels) + 1;

predictionLinearReverseWrapped = mod( ...
    predictionLinearReverse - 1, ...
    numberOfChannels) + 1;

%% =================================================
% Global baseline metrics
% ==================================================

baselineNames = [
    "First history column"
    "Last history column"
    "History mode"
    "Forward last-step extrapolation"
    "Reverse first-step extrapolation"
];

baselinePredictions = {
    predictionFirst
    predictionLast
    predictionMode
    predictionLinearForwardWrapped
    predictionLinearReverseWrapped
};

numberOfBaselines = numel( ...
    baselinePredictions);

baselineAccuracy = zeros( ...
    numberOfBaselines, ...
    1);

baselineTop5LocalAccuracy = zeros( ...
    numberOfBaselines, ...
    1);

baselineMeanAbsoluteError = zeros( ...
    numberOfBaselines, ...
    1);

baselineMedianAbsoluteError = zeros( ...
    numberOfBaselines, ...
    1);

for baselineIndex = 1:numberOfBaselines

    currentPrediction = double( ...
        baselinePredictions{baselineIndex});

    baselineAccuracy(baselineIndex) = mean( ...
        currentPrediction == targetTest) * 100;

    currentError = abs( ...
        currentPrediction - targetTest);

    baselineMeanAbsoluteError(baselineIndex) = ...
        mean(currentError);

    baselineMedianAbsoluteError(baselineIndex) = ...
        median(currentError);

    baselineTop5LocalAccuracy(baselineIndex) = mean( ...
        currentError <= 2) * 100;
end

baselineResults = table( ...
    baselineNames, ...
    baselineAccuracy, ...
    baselineTop5LocalAccuracy, ...
    baselineMeanAbsoluteError, ...
    baselineMedianAbsoluteError, ...
    'VariableNames', { ...
        'Baseline', ...
        'ExactAccuracyPct', ...
        'WithinTwoChannelsPct', ...
        'MeanAbsoluteError', ...
        'MedianAbsoluteError' ...
    });

fprintf('\n');
fprintf('============================================\n');
fprintf('GLOBAL FH BASELINES\n');
fprintf('============================================\n\n');

disp(baselineResults);

writetable( ...
    baselineResults, ...
    fullfile( ...
        resultsFolder, ...
        'fh_global_baselines.csv'));

%% =================================================
% Obtain FH pattern names
% ==================================================

uniquePatternIDs = unique( ...
    patternTest);

patternNames = strings( ...
    numel(uniquePatternIDs), ...
    1);

for patternIndex = 1:numel(uniquePatternIDs)

    currentPatternID = ...
        uniquePatternIDs(patternIndex);

    patternNames(patternIndex) = ...
        getPatternName( ...
            currentPatternID, ...
            D);
end

%% =================================================
% Baseline performance by FH pattern
% ==================================================

numberOfPatternRows = ...
    numel(uniquePatternIDs) ...
    * numberOfBaselines;

resultPatternID = zeros( ...
    numberOfPatternRows, ...
    1);

resultPatternName = strings( ...
    numberOfPatternRows, ...
    1);

resultBaselineName = strings( ...
    numberOfPatternRows, ...
    1);

resultCount = zeros( ...
    numberOfPatternRows, ...
    1);

resultAccuracy = zeros( ...
    numberOfPatternRows, ...
    1);

resultMeanError = zeros( ...
    numberOfPatternRows, ...
    1);

resultMedianError = zeros( ...
    numberOfPatternRows, ...
    1);

resultRow = 0;

fprintf('\n');
fprintf('============================================\n');
fprintf('FH BASELINES BY PATTERN\n');
fprintf('============================================\n');

for patternIndex = 1:numel(uniquePatternIDs)

    currentPatternID = ...
        uniquePatternIDs(patternIndex);

    currentPatternName = ...
        patternNames(patternIndex);

    patternMask = ...
        patternTest == currentPatternID;

    patternCount = sum( ...
        patternMask);

    fprintf('\nPattern %d: %s | n=%d\n', ...
        currentPatternID, ...
        currentPatternName, ...
        patternCount);

    for baselineIndex = 1:numberOfBaselines

        resultRow = resultRow + 1;

        currentPrediction = double( ...
            baselinePredictions{baselineIndex});

        currentPatternPrediction = ...
            currentPrediction(patternMask);

        currentPatternTarget = ...
            targetTest(patternMask);

        currentPatternError = abs( ...
            currentPatternPrediction ...
            - currentPatternTarget);

        currentAccuracy = mean( ...
            currentPatternPrediction ...
            == currentPatternTarget) * 100;

        currentMeanError = mean( ...
            currentPatternError);

        currentMedianError = median( ...
            currentPatternError);

        resultPatternID(resultRow) = ...
            currentPatternID;

        resultPatternName(resultRow) = ...
            currentPatternName;

        resultBaselineName(resultRow) = ...
            baselineNames(baselineIndex);

        resultCount(resultRow) = ...
            patternCount;

        resultAccuracy(resultRow) = ...
            currentAccuracy;

        resultMeanError(resultRow) = ...
            currentMeanError;

        resultMedianError(resultRow) = ...
            currentMedianError;

        fprintf( ...
            ['  %-34s | accuracy=%6.2f%% | ' ...
             'mean error=%7.2f\n'], ...
            baselineNames(baselineIndex), ...
            currentAccuracy, ...
            currentMeanError);
    end
end

patternBaselineResults = table( ...
    resultPatternID, ...
    resultPatternName, ...
    resultBaselineName, ...
    resultCount, ...
    resultAccuracy, ...
    resultMeanError, ...
    resultMedianError, ...
    'VariableNames', { ...
        'PatternID', ...
        'PatternName', ...
        'Baseline', ...
        'Count', ...
        'ExactAccuracyPct', ...
        'MeanAbsoluteError', ...
        'MedianAbsoluteError' ...
    });

writetable( ...
    patternBaselineResults, ...
    fullfile( ...
        resultsFolder, ...
        'fh_baselines_by_pattern.csv'));

%% =================================================
% Inspect Static and Sequential examples
% ==================================================

examplePatternIDs = [
    1
    2
];

maximumExamplesPerPattern = 10;

exampleRows = [];

fprintf('\n');
fprintf('============================================\n');
fprintf('STATIC AND SEQUENTIAL EXAMPLES\n');
fprintf('============================================\n');

for selectedPatternIndex = 1:numel(examplePatternIDs)

    selectedPatternID = ...
        examplePatternIDs(selectedPatternIndex);

    matchingRows = find( ...
        patterns == selectedPatternID, ...
        maximumExamplesPerPattern, ...
        'first');

    selectedPatternName = ...
        getPatternName( ...
            selectedPatternID, ...
            D);

    fprintf('\nPattern %d: %s\n', ...
        selectedPatternID, ...
        selectedPatternName);

    for exampleIndex = 1:numel(matchingRows)

        datasetRow = ...
            matchingRows(exampleIndex);

        currentHistory = ...
            history(datasetRow, :);

        currentTarget = ...
            targets(datasetRow);

        fprintf('Row %d | History: ', ...
            datasetRow);

        fprintf('%.0f ', ...
            currentHistory);

        fprintf('| Target: %.0f\n', ...
            currentTarget);

        exampleRows = [
            exampleRows
            datasetRow
        ];
    end
end

if ~isempty(exampleRows)

    exampleTable = array2table( ...
        history(exampleRows, :), ...
        'VariableNames', ...
        compose( ...
            'History_%02d', ...
            1:historyLength));

    exampleTable.DatasetRow = ...
        exampleRows;

    exampleTable.PatternID = ...
        patterns(exampleRows);

    exampleTable.PatternName = strings( ...
        numel(exampleRows), ...
        1);

    for exampleIndex = 1:numel(exampleRows)

        exampleTable.PatternName(exampleIndex) = ...
            getPatternName( ...
                patterns(exampleRows(exampleIndex)), ...
                D);
    end

    exampleTable.NextHop = ...
        targets(exampleRows);

    exampleTable = movevars( ...
        exampleTable, ...
        { ...
            'DatasetRow', ...
            'PatternID', ...
            'PatternName', ...
            'NextHop' ...
        }, ...
        'Before', ...
        1);

    writetable( ...
        exampleTable, ...
        fullfile( ...
            resultsFolder, ...
            'fh_static_sequential_examples.csv'));
end

%% =================================================
% Ambiguous history analysis
% ==================================================

[uniqueHistories, ~, historyGroupID] = unique( ...
    history, ...
    'rows', ...
    'stable');

numberOfUniqueHistories = size( ...
    uniqueHistories, ...
    1);

groupSampleCount = accumarray( ...
    historyGroupID, ...
    1);

groupTargetCount = zeros( ...
    numberOfUniqueHistories, ...
    1);

groupPatternCount = zeros( ...
    numberOfUniqueHistories, ...
    1);

for groupIndex = 1:numberOfUniqueHistories

    groupMask = ...
        historyGroupID == groupIndex;

    groupTargetCount(groupIndex) = numel( ...
        unique(targets(groupMask)));

    groupPatternCount(groupIndex) = numel( ...
        unique(patterns(groupMask)));
end

conflictingTargetGroups = ...
    groupTargetCount > 1;

conflictingPatternGroups = ...
    groupPatternCount > 1;

numberOfConflictingTargetGroups = sum( ...
    conflictingTargetGroups);

samplesInConflictingTargetGroups = sum( ...
    groupSampleCount( ...
        conflictingTargetGroups));

numberOfConflictingPatternGroups = sum( ...
    conflictingPatternGroups);

fprintf('\n');
fprintf('============================================\n');
fprintf('HISTORY AMBIGUITY ANALYSIS\n');
fprintf('============================================\n');

fprintf('Total samples: %d\n', ...
    numberOfSamples);

fprintf('Unique histories: %d\n', ...
    numberOfUniqueHistories);

fprintf('Repeated-history samples: %d\n', ...
    sum(groupSampleCount(groupSampleCount > 1)));

fprintf('Histories with conflicting targets: %d\n', ...
    numberOfConflictingTargetGroups);

fprintf('Samples in conflicting-target groups: %d\n', ...
    samplesInConflictingTargetGroups);

fprintf( ...
    ['Fraction of samples in conflicting-target ' ...
     'groups: %.2f%%\n'], ...
    samplesInConflictingTargetGroups ...
    / numberOfSamples ...
    * 100);

fprintf('Histories shared across multiple FH patterns: %d\n', ...
    numberOfConflictingPatternGroups);

fprintf('============================================\n');

ambiguitySummary = table( ...
    numberOfSamples, ...
    numberOfUniqueHistories, ...
    numberOfConflictingTargetGroups, ...
    samplesInConflictingTargetGroups, ...
    samplesInConflictingTargetGroups ...
        / numberOfSamples * 100, ...
    numberOfConflictingPatternGroups, ...
    'VariableNames', { ...
        'TotalSamples', ...
        'UniqueHistories', ...
        'ConflictingTargetGroups', ...
        'SamplesInConflictingTargetGroups', ...
