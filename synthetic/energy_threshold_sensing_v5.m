%% energy_threshold_sensing_v5.m
% Train and evaluate an idle-versus-occupied energy gate.
%
% Dataset encoding:
%   y_state = 0 -> idle
%   y_state = 1 -> friendly
%   y_state = 2 -> adversarial
%
% Gate encoding:
%   0 -> idle
%   1 -> occupied

clear;
clc;
close all;

datasetFile = 'dataset_v5.mat';

if ~isfile(datasetFile)
    error('Dataset file not found: %s', datasetFile);
end

%% Load only required variables

D = load( ...
    datasetFile, ...
    'X', ...
    'y_state', ...
    'train_idx', ...
    'val_idx', ...
    'test_idx');

X = single(D.X);
yState = double(D.y_state(:));

trainIdx = double(D.train_idx(:));
valIdx = double(D.val_idx(:));
testIdx = double(D.test_idx(:));

numberOfSamples = size(X, 1);

%% Validate indices

allIndices = [
    trainIdx
    valIdx
    testIdx
];

if any(allIndices < 1) || ...
        any(allIndices > numberOfSamples)

    error('Dataset split contains invalid MATLAB indices.');
end

fprintf('\n========================================\n');
fprintf('ENERGY-GATE V5 TRAINING\n');
fprintf('========================================\n');
fprintf('Dataset samples: %d\n', numberOfSamples);
fprintf('Train samples: %d\n', numel(trainIdx));
fprintf('Validation samples: %d\n', numel(valIdx));
fprintf('Test samples: %d\n', numel(testIdx));

%% Convert state labels to idle/occupied labels

% 0 = idle
% 1 = occupied: friendly or adversarial

yGate = double(yState ~= 0);

fprintf('\nGate class distribution:\n');
fprintf('Idle: %d\n', sum(yGate == 0));
fprintf('Occupied: %d\n', sum(yGate == 1));

%% Calculate energy for every I/Q window

I = X(:,:,1);
Q = X(:,:,2);

sampleEnergy = squeeze( ...
    mean(I.^2 + Q.^2, 2));

sampleEnergy = double(sampleEnergy(:));

if any(~isfinite(sampleEnergy))
    error('Non-finite energy values found in dataset.');
end

%% Training data

energyTrain = sampleEnergy(trainIdx);
labelsTrain = yGate(trainIdx);

energyVal = sampleEnergy(valIdx);
labelsVal = yGate(valIdx);

energyTest = sampleEnergy(testIdx);
labelsTest = yGate(testIdx);

%% Generate threshold candidates from training energy

numberOfCandidates = 2000;

lowEnergy = min(energyTrain);
highEnergy = max(energyTrain);

thresholdCandidates = linspace( ...
    lowEnergy, ...
    highEnergy, ...
    numberOfCandidates);

candidateBalancedAccuracy = zeros( ...
    numberOfCandidates, ...
    1);

candidateAccuracy = zeros( ...
    numberOfCandidates, ...
    1);

%% Select threshold using training balanced accuracy

for k = 1:numberOfCandidates

    currentThreshold = thresholdCandidates(k);

    predictedTrain = double( ...
        energyTrain >= currentThreshold);

    trueIdle = labelsTrain == 0;
    trueOccupied = labelsTrain == 1;

    idleRecall = mean( ...
        predictedTrain(trueIdle) == 0);

    occupiedRecall = mean( ...
        predictedTrain(trueOccupied) == 1);

    candidateBalancedAccuracy(k) = ...
        0.5 * (idleRecall + occupiedRecall);

    candidateAccuracy(k) = mean( ...
        predictedTrain == labelsTrain);
end

[bestTrainBalancedAccuracy, bestIndex] = max( ...
    candidateBalancedAccuracy);

threshold = thresholdCandidates(bestIndex);

trainAcc = candidateAccuracy(bestIndex);

%% Validation evaluation

predictedVal = double( ...
    energyVal >= threshold);

valAcc = mean( ...
    predictedVal == labelsVal);

valIdleMask = labelsVal == 0;
valOccupiedMask = labelsVal == 1;

valIdleRecall = mean( ...
    predictedVal(valIdleMask) == 0);

valOccupiedRecall = mean( ...
    predictedVal(valOccupiedMask) == 1);

valBalancedAcc = 0.5 * ( ...
    valIdleRecall + valOccupiedRecall);

%% Test evaluation

predictedTest = double( ...
    energyTest >= threshold);

testAcc = mean( ...
    predictedTest == labelsTest);

testIdleMask = labelsTest == 0;
testOccupiedMask = labelsTest == 1;

testIdleRecall = mean( ...
    predictedTest(testIdleMask) == 0);

testOccupiedRecall = mean( ...
    predictedTest(testOccupiedMask) == 1);

testBalancedAcc = 0.5 * ( ...
    testIdleRecall + testOccupiedRecall);

%% Test confusion matrix

% Rows: true
% Columns: predicted
% Order: idle, occupied

gateConfusionMatrix = confusionmat( ...
    labelsTest, ...
    predictedTest, ...
    'Order', [0 1]);

%% Print results

fprintf('\n========================================\n');
fprintf('ENERGY-GATE RESULTS\n');
fprintf('========================================\n');

fprintf('Selected threshold: %.8f\n', threshold);

fprintf('\nTraining:\n');
fprintf('Accuracy: %.2f%%\n', trainAcc * 100);
fprintf( ...
    'Balanced accuracy: %.2f%%\n', ...
    bestTrainBalancedAccuracy * 100);

fprintf('\nValidation:\n');
fprintf('Accuracy: %.2f%%\n', valAcc * 100);
fprintf( ...
    'Balanced accuracy: %.2f%%\n', ...
    valBalancedAcc * 100);
fprintf( ...
    'Idle recall: %.2f%%\n', ...
    valIdleRecall * 100);
fprintf( ...
    'Occupied recall: %.2f%%\n', ...
    valOccupiedRecall * 100);

fprintf('\nTest:\n');
fprintf('Accuracy: %.2f%%\n', testAcc * 100);
fprintf( ...
    'Balanced accuracy: %.2f%%\n', ...
    testBalancedAcc * 100);
fprintf( ...
    'Idle recall: %.2f%%\n', ...
    testIdleRecall * 100);
fprintf( ...
    'Occupied recall: %.2f%%\n', ...
    testOccupiedRecall * 100);

fprintf('\nTest confusion matrix:\n');
fprintf('Rows = true, columns = predicted\n');
fprintf('Order = idle, occupied\n');
disp(gateConfusionMatrix);

%% Plot training energy distributions

figure('Color', 'white');

histogram( ...
    energyTrain(labelsTrain == 0), ...
    100, ...
    'Normalization', 'probability', ...
    'DisplayName', 'Idle');

hold on;

histogram( ...
    energyTrain(labelsTrain == 1), ...
    100, ...
    'Normalization', 'probability', ...
    'DisplayName', 'Occupied');

xline( ...
    threshold, ...
    'r--', ...
    'LineWidth', 2, ...
    'DisplayName', 'Selected threshold');

grid on;
legend('Location', 'best');

title('Dataset V5 Energy-Gate Training Distribution');
xlabel('Mean I/Q Energy');
ylabel('Probability');

exportgraphics( ...
    gcf, ...
    'energy_gate_v5_distribution.png', ...
    'Resolution', 200);

%% Test confusion chart

trueGateTest = categorical( ...
    labelsTest, ...
    [0 1], ...
    {'idle', 'occupied'});

predGateTest = categorical( ...
    predictedTest, ...
    [0 1], ...
    {'idle', 'occupied'});

figure('Color', 'white');

chart = confusionchart( ...
    trueGateTest, ...
    predGateTest);

chart.Title = sprintf( ...
    'Energy Gate V5 Test Accuracy: %.2f%%', ...
    testAcc * 100);

chart.RowSummary = 'row-normalized';
chart.ColumnSummary = 'column-normalized';

exportgraphics( ...
    gcf, ...
    'energy_gate_v5_confusion.png', ...
    'Resolution', 200);

%% Save gate model

save( ...
    'energy_gate_v5.mat', ...
    'threshold', ...
    'trainAcc', ...
    'bestTrainBalancedAccuracy', ...
    'valAcc', ...
    'valBalancedAcc', ...
    'valIdleRecall', ...
    'valOccupiedRecall', ...
    'testAcc', ...
    'testBalancedAcc', ...
    'testIdleRecall', ...
    'testOccupiedRecall', ...
    'gateConfusionMatrix');

%% Save summary CSV

resultsTable = table( ...
    threshold, ...
    trainAcc * 100, ...
    bestTrainBalancedAccuracy * 100, ...
    valAcc * 100, ...
    valBalancedAcc * 100, ...
    testAcc * 100, ...
    testBalancedAcc * 100, ...
    testIdleRecall * 100, ...
    testOccupiedRecall * 100, ...
    'VariableNames', { ...
        'Threshold', ...
        'TrainAccuracyPercent', ...
        'TrainBalancedAccuracyPercent', ...
        'ValidationAccuracyPercent', ...
        'ValidationBalancedAccuracyPercent', ...
        'TestAccuracyPercent', ...
        'TestBalancedAccuracyPercent', ...
        'TestIdleRecallPercent', ...
        'TestOccupiedRecallPercent' ...
        });

writetable( ...
    resultsTable, ...
    'energy_gate_v5_results.csv');

fprintf('\nSaved files:\n');
fprintf('- energy_gate_v5.mat\n');
fprintf('- energy_gate_v5_results.csv\n');
fprintf('- energy_gate_v5_distribution.png\n');
fprintf('- energy_gate_v5_confusion.png\n');